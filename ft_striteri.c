#include "libft.h"

void	ft_striteri(char *s, void (*f)(unsigned int, char *))
{
	unsigned int	i;

	if (!s || !f)
		return ;
	i = 0;
	while (s[i])
	{
		f(i, &s[i]);
		i++;
	}
}
// Wendet eine Funktion auf jedes Zeichen eines Strings an und
// übergibt den Index und die Adresse des Zeichens.
